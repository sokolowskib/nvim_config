vim.keymap.set('n', '<leader>.', ':vertical resize +2<CR>')

vim.keymap.set('n', '<leader>tr', function()
	vim.cmd('botright vsplit | terminal')
	vim.cmd('vertical resize ' .. math.floor(vim.o.columns * 0.25))
	vim.cmd('startinsert')
end, { desc = '25% terminal on right' })
